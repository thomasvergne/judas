use std::collections::{HashMap, HashSet};
use std::fmt::Write;

use judas_ast::expr::Literal;
use judas_ast::item::PortDirection;
use judas_ast::stmt::EdgeKind;
use judas_infer::{
    ResolvedType, TypedCallArg, TypedEnumDecl, TypedExpr, TypedExprKind, TypedInterfaceDecl,
    TypedItem, TypedItemKind, TypedModuleDecl, TypedModuleItemKind, TypedSourceFile,
    TypedStructDecl,
};

use crate::context::{VerilogGenerator, qualify_name, sanitize_ident};

impl VerilogGenerator {
    pub fn emit_source_file(&mut self, source: &TypedSourceFile) -> String {
        // 1. Collect all declarations from imported files and current file
        self.collect_items(&source.imported_items, "");
        self.collect_items(&source.items, "");

        let mut out = String::new();
        let _ = writeln!(out, "// Generated by Judas HDL Compiler");
        let _ = writeln!(out, "`default_nettype none\n");

        // Pre-collect module names defined in the main source file so imported files don't shadow them
        let mut main_module_names = HashSet::new();
        Self::collect_module_names(&source.items, "", &mut main_module_names);

        // 2. Emit imported items (modules, etc.) first
        let mut emitted_modules = main_module_names;
        self.emit_items(&source.imported_items, "", &mut out, &mut emitted_modules);

        // 3. Emit items from the main source file
        emitted_modules.clear();
        self.emit_items(&source.items, "", &mut out, &mut emitted_modules);

        let _ = writeln!(out, "`default_nettype wire");
        out
    }

    fn emit_items(
        &mut self,
        items: &[TypedItem],
        prefix: &str,
        out: &mut String,
        emitted_modules: &mut HashSet<String>,
    ) {
        for item in items {
            match &item.kind {
                TypedItemKind::Enum(enum_decl) => {
                    self.emit_enum_comment(enum_decl, prefix, out);
                }
                TypedItemKind::Struct(struct_decl) => {
                    self.emit_struct_comment(struct_decl, prefix, out);
                }
                TypedItemKind::Interface(iface_decl) => {
                    self.emit_interface_comment(iface_decl, prefix, out);
                }
                TypedItemKind::Module(mod_decl) => {
                    let full_name = qualify_name(prefix, &mod_decl.name.name);
                    let v_name = sanitize_ident(&full_name);
                    if emitted_modules.insert(v_name) {
                        self.emit_module(mod_decl, prefix, out);
                    }
                }
                TypedItemKind::Namespace(ns_decl) => {
                    let next_prefix = qualify_name(prefix, &ns_decl.name.name);
                    self.emit_items(&ns_decl.items, &next_prefix, out, emitted_modules);
                }
                TypedItemKind::Import(_) => {}
            }
        }
    }

    fn emit_enum_comment(&self, enum_decl: &TypedEnumDecl, prefix: &str, out: &mut String) {
        let full_name = qualify_name(prefix, &enum_decl.name.name);
        let width = self.enums.get(&full_name).map(|e| e.width).unwrap_or(1);
        let _ = writeln!(out, "// Enum `{}` ({}-bit)", full_name, width);
        for v in &enum_decl.variants {
            let _ = writeln!(out, "//   {} = {}'d{}", v.name.name, width, v.discriminant);
        }
        let _ = writeln!(out);
    }

    fn emit_struct_comment(&self, struct_decl: &TypedStructDecl, prefix: &str, out: &mut String) {
        let full_name = qualify_name(prefix, &struct_decl.name.name);
        let _ = writeln!(
            out,
            "// Packed Struct `{}` (total width: {})",
            full_name, struct_decl.total_width
        );
    }

    fn emit_interface_comment(
        &self,
        iface_decl: &TypedInterfaceDecl,
        prefix: &str,
        out: &mut String,
    ) {
        let full_name = qualify_name(prefix, &iface_decl.name.name);
        let _ = writeln!(out, "// Interface `{}`", full_name);
    }

    fn emit_module(&mut self, module: &TypedModuleDecl, prefix: &str, out: &mut String) {
        let full_name = qualify_name(prefix, &module.name.name);
        let verilog_name = sanitize_ident(&full_name);

        if module.is_extern {
            if let Some(path) = &module.foreign_path {
                let _ = writeln!(
                    out,
                    "// External Verilog module `{}` imported from \"{}\"\n",
                    verilog_name, path
                );
            } else {
                let _ = writeln!(out, "// External Verilog module `{}`\n", verilog_name);
            }
            return;
        }

        self.procedural_lets.clear();
        self.current_interface_ports.clear();
        self.current_instances.clear();

        // Record interface ports and submodule instances in current module
        for item in &module.items {
            match &item.kind {
                TypedModuleItemKind::InterfacePort(ip) => {
                    self.current_interface_ports.insert(ip.name.name.clone());
                }
                TypedModuleItemKind::Let(let_decl) => {
                    if matches!(let_decl.ty, ResolvedType::ModuleInstance { .. }) {
                        self.current_instances.insert(let_decl.name.name.clone());
                    }
                }
                _ => {}
            }
        }

        // Collect all signals assigned inside `on` blocks so we know which output ports must be `output reg`
        let mut assigned_in_on = HashSet::new();
        let mut procedural_let_decls = Vec::new();
        for item in &module.items {
            if let TypedModuleItemKind::On(on_block) = &item.kind {
                self.collect_on_block_targets(
                    &on_block.body,
                    &mut assigned_in_on,
                    &mut procedural_let_decls,
                );
            }
        }
        for (let_name, _) in &procedural_let_decls {
            self.procedural_lets.insert(let_name.clone());
        }

        // Emit module header & parameters
        if module.params.is_empty() {
            let _ = writeln!(out, "module {} (", verilog_name);
        } else {
            let _ = writeln!(out, "module {} #(", verilog_name);
            for (idx, param) in module.params.iter().enumerate() {
                let comma = if idx + 1 < module.params.len() {
                    ","
                } else {
                    ""
                };
                let def_val = param.default.unwrap_or(0);
                let _ = writeln!(out, "    parameter {} = {}{}", param.name.name, def_val, comma);
            }
            let _ = writeln!(out, ") (");
        }

        // Flatten all ports (regular ports + interface ports)
        let mut port_lines = Vec::new();
        for item in &module.items {
            match &item.kind {
                TypedModuleItemKind::Port(port) => {
                    let dir_str = match port.direction {
                        PortDirection::Input => "input wire",
                        PortDirection::Output => {
                            if assigned_in_on.contains(&port.name.name) {
                                "output reg"
                            } else {
                                "output wire"
                            }
                        }
                    };
                    let type_spec = self.format_type_spec(&port.ty);
                    if type_spec.is_empty() {
                        port_lines.push(format!("    {} {}", dir_str, port.name.name));
                    } else {
                        port_lines.push(format!("    {} {} {}", dir_str, type_spec, port.name.name));
                    }
                }
                TypedModuleItemKind::InterfacePort(ip) => {
                    for (dir, sig_name, sig_ty) in &ip.signals {
                        let flat_name = format!("{}_{}", ip.name.name, sig_name);
                        let dir_str = match dir {
                            PortDirection::Input => "input wire",
                            PortDirection::Output => {
                                if assigned_in_on.contains(&flat_name) {
                                    "output reg"
                                } else {
                                    "output wire"
                                }
                            }
                        };
                        let type_spec = self.format_type_spec(sig_ty);
                        if type_spec.is_empty() {
                            port_lines.push(format!("    {} {}", dir_str, flat_name));
                        } else {
                            port_lines.push(format!("    {} {} {}", dir_str, type_spec, flat_name));
                        }
                    }
                }
                _ => {}
            }
        }

        for (idx, line) in port_lines.iter().enumerate() {
            let comma = if idx + 1 < port_lines.len() { "," } else { "" };
            let _ = writeln!(out, "{}{}", line, comma);
        }
        let _ = writeln!(out, ");");

        // 1. Emit registers
        for item in &module.items {
            if let TypedModuleItemKind::Register(reg) = &item.kind {
                match &reg.ty {
                    ResolvedType::Array { element, size } => {
                        let elem_spec = self.format_type_spec(element);
                        let size_msb = self.format_msb(size);
                        if elem_spec.is_empty() {
                            let _ = writeln!(out, "    reg {} [0:{}];", reg.name.name, size_msb);
                        } else {
                            let _ = writeln!(
                                out,
                                "    reg {} {} [0:{}];",
                                elem_spec, reg.name.name, size_msb
                            );
                        }
                    }
                    _ => {
                        let type_spec = self.format_type_spec(&reg.ty);
                        let reset_str = self.emit_expr(&reg.reset_value);
                        if type_spec.is_empty() {
                            let _ = writeln!(out, "    reg {} = {};", reg.name.name, reset_str);
                        } else {
                            let _ = writeln!(
                                out,
                                "    reg {} {} = {};",
                                type_spec, reg.name.name, reset_str
                            );
                        }
                    }
                }
            }
        }

        // 2. Emit procedural temporary regs for `let` inside `on` blocks
        for (let_name, let_ty) in &procedural_let_decls {
            let type_spec = self.format_type_spec(let_ty);
            if type_spec.is_empty() {
                let _ = writeln!(out, "    reg {};", let_name);
            } else {
                let _ = writeln!(out, "    reg {} {};", type_spec, let_name);
            }
        }

        // 3. Emit combinational `let` wires and Submodule instantiations
        self.emit_lets_and_instances(module, out);

        // 4. Emit continuous assignments (`assign`) from port initializers and module-level connections
        for item in &module.items {
            match &item.kind {
                TypedModuleItemKind::Port(port) => {
                    if let Some(init) = &port.initializer {
                        let val_str = self.emit_expr(init);
                        let _ = writeln!(out, "    assign {} = {};", port.name.name, val_str);
                    }
                }
                TypedModuleItemKind::Connection(conn) => {
                    if self.is_instance_connection(&conn.target, &conn.value) {
                        continue;
                    }
                    let target_str = self.emit_expr(&conn.target);
                    let val_str = self.emit_expr(&conn.value);
                    let _ = writeln!(out, "    assign {} = {};", target_str, val_str);
                }
                _ => {}
            }
        }

        // 5. Emit `on` blocks (`always @(posedge/negedge clk)`)
        for item in &module.items {
            if let TypedModuleItemKind::On(on_block) = &item.kind {
                let edge_kw = match on_block.trigger.edge {
                    EdgeKind::Rising => "posedge",
                    EdgeKind::Falling => "negedge",
                };
                let clk_str = self.emit_expr(&on_block.trigger.signal);
                let _ = writeln!(out, "\n    always @({} {}) begin", edge_kw, clk_str);
                for stmt in &on_block.body {
                    self.emit_stmt(stmt, 2, out);
                }
                let _ = writeln!(out, "    end");
            }
        }

        // 6. Emit module-level assertions
        for item in &module.items {
            if let TypedModuleItemKind::Assert(assert_decl) = &item.kind {
                let cond_str = self.emit_expr(&assert_decl.condition);
                let msg = assert_decl
                    .message
                    .as_deref()
                    .unwrap_or("Assertion failed");
                let _ = writeln!(out, "\n    `ifndef SYNTHESIS");
                let _ = writeln!(out, "    always @(*) begin");
                let _ = writeln!(out, "        if (!({})) begin", cond_str);
                let _ = writeln!(out, "            $display(\"Assertion failed: {}\");", msg);
                let _ = writeln!(out, "            $finish;");
                let _ = writeln!(out, "        end");
                let _ = writeln!(out, "    end");
                let _ = writeln!(out, "    `endif");
            }
        }

        let _ = writeln!(out, "endmodule\n");
    }

    fn emit_lets_and_instances(&self, module: &TypedModuleDecl, out: &mut String) {
        let mut instance_input_drivers: HashMap<(String, String), String> = HashMap::new();

        for item in &module.items {
            if let TypedModuleItemKind::Connection(conn) = &item.kind {
                // Case 1: Interface bundle connection `connect rom.bus = cpu.bus`
                if let (
                    TypedExprKind::FieldAccess {
                        base: target_base,
                        field: target_field,
                    },
                    TypedExprKind::FieldAccess {
                        base: val_base,
                        field: val_field,
                    },
                ) = (&conn.target.kind, &conn.value.kind)
                    && let (TypedExprKind::Ident(t_inst), TypedExprKind::Ident(v_inst)) =
                        (&target_base.kind, &val_base.kind)
                    && let ResolvedType::InterfaceInstance { signals, .. } = &conn.target.ty
                {
                    for (sig_name, (dir, _sig_ty)) in signals {
                        let t_port = format!("{}_{}", target_field.name, sig_name);
                        let v_port = format!("{}_{}", val_field.name, sig_name);
                        match dir {
                            PortDirection::Input => {
                                instance_input_drivers.insert(
                                    (t_inst.name.clone(), t_port),
                                    format!("{}_{}", v_inst.name, v_port),
                                );
                            }
                            PortDirection::Output => {
                                instance_input_drivers.insert(
                                    (v_inst.name.clone(), v_port),
                                    format!("{}_{}", t_inst.name, t_port),
                                );
                            }
                        }
                    }
                    continue;
                }

                // Case 2: Single port connection `connect counter.clk = clk`
                if let TypedExprKind::FieldAccess { base, field } = &conn.target.kind
                    && let TypedExprKind::Ident(inst_id) = &base.kind
                    && self.current_instances.contains(&inst_id.name)
                {
                    let val_str = self.emit_expr(&conn.value);
                    instance_input_drivers
                        .insert((inst_id.name.clone(), field.name.clone()), val_str);
                }
            }
        }

        // Pass 1: Emit all combinational `let` wires and all submodule output interconnect wires first
        let mut pending_instances = Vec::new();

        for item in &module.items {
            if let TypedModuleItemKind::Let(let_decl) = &item.kind {
                if let ResolvedType::ModuleInstance {
                    module_name,
                    ports: inst_ports_map,
                } = &let_decl.ty
                {
                    let inst_name = &let_decl.name.name;
                    let mod_info = self.modules.get(module_name).cloned();
                    let verilog_mod_name = mod_info
                        .as_ref()
                        .map(|m| m.verilog_name.clone())
                        .unwrap_or_else(|| sanitize_ident(module_name));

                    let call_args: &[TypedCallArg] = match &let_decl.value.kind {
                        TypedExprKind::Call { args, .. } => args,
                        _ => &[],
                    };

                    let param_names: HashSet<String> = mod_info
                        .as_ref()
                        .map(|m| m.params.iter().map(|(n, _)| n.clone()).collect())
                        .unwrap_or_default();

                    let mut param_overrides = Vec::new();
                    let mut inline_port_drivers = HashMap::new();

                    for arg in call_args {
                        if let Some(arg_ident) = &arg.name {
                            if param_names.contains(&arg_ident.name)
                                || !inst_ports_map.contains_key(&arg_ident.name)
                            {
                                let val_str = match &arg.value.kind {
                                    TypedExprKind::Literal(Literal::Integer(i)) => i.to_string(),
                                    _ => self.emit_expr(&arg.value),
                                };
                                param_overrides.push((arg_ident.name.clone(), val_str));
                            } else {
                                let val_str = self.emit_expr(&arg.value);
                                inline_port_drivers.insert(arg_ident.name.clone(), val_str);
                            }
                        }
                    }

                    let mut flat_ports: Vec<(PortDirection, String, ResolvedType)> = Vec::new();
                    if let Some(info) = &mod_info {
                        for (dir, p_name, p_ty) in &info.ports {
                            let actual_ty = inst_ports_map
                                .get(p_name)
                                .map(|(_, t)| t.clone())
                                .unwrap_or_else(|| p_ty.clone());
                            flat_ports.push((*dir, p_name.clone(), actual_ty));
                        }
                        for ip_info in &info.interface_ports {
                            for (s_dir, s_name, s_ty) in &ip_info.signals {
                                flat_ports.push((
                                    *s_dir,
                                    format!("{}_{}", ip_info.port_name, s_name),
                                    s_ty.clone(),
                                ));
                            }
                        }
                    } else {
                        let mut sorted_keys: Vec<_> = inst_ports_map.keys().cloned().collect();
                        sorted_keys.sort();
                        for k in sorted_keys {
                            let (dir, ty) = &inst_ports_map[&k];
                            flat_ports.push((*dir, k, ty.clone()));
                        }
                    }

                    for (dir, p_name, p_ty) in &flat_ports {
                        if *dir == PortDirection::Output {
                            let wire_name = format!("{}_{}", inst_name, p_name);
                            let type_spec = self.format_type_spec(p_ty);
                            if type_spec.is_empty() {
                                let _ = writeln!(out, "    wire {};", wire_name);
                            } else {
                                let _ = writeln!(out, "    wire {} {};", type_spec, wire_name);
                            }
                        }
                    }

                    pending_instances.push((
                        verilog_mod_name,
                        inst_name.clone(),
                        param_overrides,
                        flat_ports,
                        inline_port_drivers,
                    ));
                } else {
                    let type_spec = self.format_type_spec(&let_decl.ty);
                    let val_str = self.emit_expr(&let_decl.value);
                    if type_spec.is_empty() {
                        let _ = writeln!(out, "    wire {} = {};", let_decl.name.name, val_str);
                    } else {
                        let _ = writeln!(
                            out,
                            "    wire {} {} = {};",
                            type_spec, let_decl.name.name, val_str
                        );
                    }
                }
            }
        }

        // Pass 2: Emit all submodule instantiations after all interconnect wires are declared
        for (verilog_mod_name, inst_name, param_overrides, flat_ports, inline_port_drivers) in
            pending_instances
        {
            if param_overrides.is_empty() {
                let _ = writeln!(out, "\n    {} {} (", verilog_mod_name, inst_name);
            } else {
                let _ = writeln!(out, "\n    {} #(", verilog_mod_name);
                for (idx, (p_name, p_val)) in param_overrides.iter().enumerate() {
                    let comma = if idx + 1 < param_overrides.len() {
                        ","
                    } else {
                        ""
                    };
                    let _ = writeln!(out, "        .{}({}){}", p_name, p_val, comma);
                }
                let _ = writeln!(out, "    ) {} (", inst_name);
            }

            for (idx, (dir, p_name, p_ty)) in flat_ports.iter().enumerate() {
                let comma = if idx + 1 < flat_ports.len() { "," } else { "" };
                let conn_expr = match dir {
                    PortDirection::Output => format!("{}_{}", inst_name, p_name),
                    PortDirection::Input => inline_port_drivers
                        .get(p_name)
                        .cloned()
                        .or_else(|| {
                            instance_input_drivers
                                .get(&(inst_name.clone(), p_name.clone()))
                                .cloned()
                        })
                        .unwrap_or_else(|| {
                            let w = self.concrete_width_of(p_ty).unwrap_or(1);
                            format!("{}'b0", w)
                        }),
                };
                let _ = writeln!(out, "        .{}({}){}", p_name, conn_expr, comma);
            }
            let _ = writeln!(out, "    );");
        }
    }

    fn is_instance_connection(&self, target: &TypedExpr, value: &TypedExpr) -> bool {
        if matches!(target.ty, ResolvedType::InterfaceInstance { .. })
            && matches!(value.ty, ResolvedType::InterfaceInstance { .. })
        {
            return true;
        }
        if let TypedExprKind::FieldAccess { base, .. } = &target.kind
            && let TypedExprKind::Ident(id) = &base.kind
            && self.current_instances.contains(&id.name)
        {
            return true;
        }
        false
    }
}
